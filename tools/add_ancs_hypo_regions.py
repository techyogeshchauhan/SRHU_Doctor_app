"""
tools/add_ancs_hypo_regions.py

Adds (or replaces) the curated regions of the ANCS and Neonatal Hypoglycemia
STW posters in assets/regions/regions.json. Boxes are the PDF's own card
rectangles (vector drawings, in PDF points), padded by 2 pt and normalised to
the page size. Run tools/build_region_text.py afterwards to fill "text" and
render the crops:

    python tools/add_ancs_hypo_regions.py
    python tools/build_region_text.py \
        Antenatal_Corticosteroids_for_Preterm_Birth_8th_Oct.pdf \
        Neonatal_Hypoglycemia_8th_Oct.pdf
"""

import json
import os
