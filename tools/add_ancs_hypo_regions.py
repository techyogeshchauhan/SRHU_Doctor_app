def main():
    with open(REGIONS_JSON_PATH, "r", encoding="utf-8") as f:
        regions = json.load(f)
    keep = [r for r in regions if r["document"] not in (ANCS_DOC, HYPO_DOC)]
    merged = keep + ANCS + HYPO
    with open(REGIONS_JSON_PATH, "w", encoding="utf-8") as f:
        json.dump(merged, f, indent=2, ensure_ascii=False)
    print(f"{len(keep)} existing + {len(ANCS)} ANCS + {len(HYPO)} hypoglycemia "
          f"regions -> {REGIONS_JSON_PATH}")


if __name__ == "__main__":
    main()
