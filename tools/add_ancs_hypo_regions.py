if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8")

PROJECT_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
REGIONS_JSON_PATH = os.path.join(PROJECT_ROOT, "assets", "regions", "regions.json")

ANCS_DOC = "Antenatal_Corticosteroids_for_Preterm_Birth_8th_Oct.pdf"
HYPO_DOC = "Neonatal_Hypoglycemia_8th_Oct.pdf"
PAGE_W, PAGE_H = 841.89, 1633.68  # both posters
PAD = 2.0


def region(rid, doc, title, rtype, section, box, aliases, questions):
    x0, y0, x1, y1 = box
    x0, y0 = max(0.0, x0 - PAD), max(0.0, y0 - PAD)
    x1, y1 = min(PAGE_W, x1 + PAD), min(PAGE_H, y1 + PAD)
    return {
        "id": rid,
        "document": doc,
        "page": 1,
        "title": title,
        "type": rtype,
        "section": section,
        "x": round(x0 / PAGE_W, 5),
        "y": round(y0 / PAGE_H, 5),
        "w": round((x1 - x0) / PAGE_W, 5),
        "h": round((y1 - y0) / PAGE_H, 5),
        "aliases": aliases,
        "example_questions": questions,
    }


