def main():
    with open(REGIONS_PATH, encoding="utf-8") as f:
        regions = json.load(f)
    added_ids = {r["id"] for r in TRIAGE + KMC}
    regions = [r for r in regions if r["id"] not in added_ids]
    regions.extend(TRIAGE)
    regions.extend(KMC)
    with open(REGIONS_PATH, "w", encoding="utf-8") as f:
        json.dump(regions, f, indent=2, ensure_ascii=False)
    print(f"Added {len(added_ids)} Triage/KMC chatbot regions")


if __name__ == "__main__":
    main()
