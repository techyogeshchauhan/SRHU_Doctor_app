def region(rid, doc, title, section, box, aliases, questions, intents,
           region_type="text", manual_content=None):
    x0, y0, x1, y1 = box
    return {
        "id": rid,
        "document": doc,
        "page": 1,
        "title": title,
        "type": region_type,
        "section": section,
        "x": round(max(0, x0) / PAGE_W, 5),
        "y": round(max(0, y0) / PAGE_H, 5),
        "w": round((min(PAGE_W, x1) - max(0, x0)) / PAGE_W, 5),
        "h": round((min(PAGE_H, y1) - max(0, y0)) / PAGE_H, 5),
        "aliases": aliases,
        "example_questions": questions,
        "intents": intents,
        **({"manual_content": manual_content} if manual_content else {}),
    }


